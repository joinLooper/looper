/**
 * F1 original-art ingestion. Zero image generation and zero resampling.
 * Usage: node scripts/f1-ingest-assets.mjs --source "C:\path\to\approved\pngs"
 *
 * Copy all 6 exact-named originals as a single validated set. Run only in a
 * clean, authorized worktree. Review SHA report with the art owner before PASS.
 */
import { createHash } from "node:crypto";
import { readFileSync, existsSync, mkdirSync, writeFileSync, copyFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const sourceIdx=process.argv.indexOf("--source");
const source=sourceIdx>=0?process.argv[sourceIdx+1]:process.env.F1_ORIGINALS_DIR;
if(!source){console.error("Missing --source with exact original PNG directory.");process.exit(2);}
const outDir=join(root,"assets","f1");
const outputs=[
 {id:"scene_forest_clearing_base",name:"陽光瀑布森林秘境.png",out:"forest-clearing-base.png",background:true},
 {id:"f1_sprout_info_stage_01",name:"可愛種子萌芽土丘圖示.png",out:"sprout-info-stage-01.png"},
 {id:"f1_sprout_info_stage_02",name:"透明背景的雙葉幼苗土丘圖示.png",out:"sprout-info-stage-02.png"},
 {id:"f1_sprout_info_stage_03",name:"卡通風格三葉幼苗土堆.png",out:"sprout-info-stage-03.png"},
 {id:"f1_sprout_info_stage_04",name:"透明背景上的立體嫩芽土丘.png",out:"sprout-info-stage-04.png"},
 {id:"f1_sprout_info_stage_05",name:"陽光下的四葉幼苗土丘.png",out:"sprout-info-stage-05.png"}
];
function inspect(file){
 const b=readFileSync(file);
 if(b.length<33||b.subarray(0,8).toString("hex")!=="89504e470d0a1a0a"||b.toString("ascii",12,16)!=="IHDR")throw Error("Not a valid PNG header: "+file);
 const w=b.readUInt32BE(16),h=b.readUInt32BE(20),colorType=b[25];
 if(w<64||h<64||w>10000||h>10000)throw Error("Invalid dimensions: "+file);
 const hasAlpha=colorType===4||colorType===6||(colorType===3&&b.includes(Buffer.from("tRNS")));
 return {bytes:b.length,width:w,height:h,colorType,hasAlpha,sha256:createHash("sha256").update(b).digest("hex")};
}
const validated=[];
for(const item of outputs){
 const src=join(resolve(source),item.name);
 if(!existsSync(src))throw Error("SOURCE_MISSING: "+src);
 const facts=inspect(src);
 if(item.background && (facts.width!==941||facts.height!==1672)) throw Error("Unexpected F1 background size; confirm asset provenance: "+item.name+" "+facts.width+"x"+facts.height);
 if(!item.background&&!facts.hasAlpha)throw Error("Info stage must be transparent PNG: "+item.name);
 validated.push({...item,source:src,...facts});
}
mkdirSync(outDir,{recursive:true});
for(const item of validated){
 const dest=join(outDir,item.out);
 if(existsSync(dest)){
   const prev=inspect(dest);
   if(prev.sha256!==item.sha256)throw Error("Existing asset differs; manual resolution required: "+dest);
 }else copyFileSync(item.source,dest);
}
const text=[
 '/* AUTO-GENERATED by scripts/f1-ingest-assets.mjs. Original PNG bytes only. */',
 'import type { ImageSourcePropType } from "react-native";',
 'import type { SproutStage } from "./f1-sprout-assets";',
 'export const APPROVED_F1_BACKGROUND: ImageSourcePropType | null = require("../assets/f1/forest-clearing-base.png");',
 'export const APPROVED_F1_SPROUT_INFO_IMAGES: Readonly<Partial<Record<SproutStage, ImageSourcePropType>>> = Object.freeze({',
 ...validated.slice(1).map((item,i)=>'  '+(i+1)+': require("../assets/f1/'+item.out+'"),'),
 '});',''
].join("\n");
writeFileSync(join(root,"src","f1-runtime-art.generated.ts"),text,"utf8");
const audit={
 batchId:"APP-MERGE-F1-SPROUT-INFO-01",sourceDirectory:resolve(source),
 reviewStatus:"AWAITING_HUMAN_ART_SOURCE_CONFIRMATION",
 backgroundWorldObject:"scene_forest_clearing_base",
 stageAssetsInfoOnly:true,formalLedgerTouched:false,
 assets:validated.map(({id,name,out,width,height,colorType,bytes,sha256})=>({assetId:id,originalFilename:name,bundlePath:"assets/f1/"+out,width,height,colorType,bytes,sha256}))
};
writeFileSync(join(outDir,"f1-originals.sha256.manifest.json"),JSON.stringify(audit,null,2)+"\n");
console.log(JSON.stringify({status:"INGESTED_PENDING_HUMAN_ART_REVIEW",assets:audit.assets},null,2));
