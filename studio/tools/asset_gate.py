#!/usr/bin/env python3
"""Looper Studio immutable-authority contract check. Stdlib only.

Structure PASS is NOT art approval. Release returns 4 while approvals are HOLD.
No file is modified and no source image is generated by this program.
"""
import argparse
import hashlib
import json
from pathlib import Path

EXPECTED_SCENES = ["forest_clearing", "treehouse_main"]
FSSL = ["NATURE_FIRST", "ANIMAL_NATIVE", "SOFT_ORGANIC", "LIVED_IN", "EVERYDAY_NOT_FANTASY"]
LAYERS = ["bg_far", "bg_structure", "ground", "prop_back", "contact_shadow",
          "actor", "prop_front", "fx_atmosphere", "fx_light", "ui"]
REQUIRED_SLOTS = {"forest_clean_plate", "marmot_editable_master",
                  "actor_contact_shadow", "knowledge_book_editable_layers"}
HOLD_FIELDS = ("artGate", "spriteGate", "fusionGate", "appIntegrationGate")
APPROVAL_FIELDS = ("founderSceneFusion", "founderAnimation",
                   "founderMobileArtwork", "realDeviceQa")
ALLOWED_STATUSES = {"MISSING_NATIVE_MASTER", "SOURCE_QA_ONLY",
                    "ART_CANDIDATE", "FOUNDER_APPROVED"}


def verify(document: dict, root: Path, release: bool = False) -> tuple[list[str], list[str]]:
    """Return (structural errors, release blockers)."""
    errors, blockers = [], []
    world = document.get("world", {})
    slice_data = document.get("slice", {})
    if document.get("classification") != "ENGINEERING_CONTRACT_NOT_ART_AUTHORITY":
        errors.append("合同不能冒充最高美術權威")
    if world.get("sceneIds") != EXPECTED_SCENES:
        errors.append("不得新增、重命名或調換正式場景 ID")
    if world.get("logicalCanvas") != {"width": 1000, "height": 1000}:
        errors.append("Logical Canvas 必須保持 1000x1000")
    if world.get("playSafe") != {"xMin": 80, "xMax": 920, "yMin": 160, "yMax": 860}:
        errors.append("Play Safe 範圍與權威不同")
    if world.get("fssl") != FSSL or world.get("layerOrder") != LAYERS:
        errors.append("FSSL 或畫面層級順序變動")
    for field in ("cameraPxPerCm", "lightKelvin"):
        if world.get(field) is not None:
            errors.append(f"{field} 尚無授權測量值，不得自行填入")
    if world.get("treehouseWindowAuthority") is not None:
        errors.append("Treehouse 窗位尚未取得唯一裁決")
    if slice_data.get("sceneId") != "forest_clearing" or slice_data.get("targetLevel") != 1:
        errors.append("此批僅能使用 Lv1 Forest 正式場景")
    if slice_data.get("mode") != "ENGINEERING_ISOLATED":
        errors.append("本批必須維持獨立工程試驗")
    if slice_data.get("ipSourcePolicy") != "APPROVED_MASTER_ONLY":
        errors.append("禁止用相似 AI 圖取代核准角色")
    if slice_data.get("engineDecision") != "CANDIDATE_UNITY_VS_NATIVE_INTEGRATION":
        errors.append("禁止把 Unity 候選擅自升格正式引擎裁決")
    if not isinstance(slice_data.get("interactionIds"), list) or set(slice_data["interactionIds"]) != {"knowledge_book_open", "knowledge_book_close"}:
        errors.append("本批測試不得添加未授權事件")
    assets = document.get("assets", [])
    if not isinstance(assets, list):
        return errors + ["assets 應為陣列"], blockers
    slots = [a.get("slot") for a in assets if isinstance(a, dict)]
    if len(slots) != len(set(slots)) or set(slots) != REQUIRED_SLOTS:
        errors.append("原生素材工程插槽有重複、遺漏或擅自新增")
    root = root.resolve()
    for item in assets:
        if not isinstance(item, dict):
            errors.append("assets 條目格式錯誤")
            continue
        slot = item.get("slot", "?")
        if item.get("status") not in ALLOWED_STATUSES:
            errors.append(f"{slot}: 非法狀態")
        approved = item.get("sourceApproved") is True and item.get("artApproved") is True
        if item.get("status") == "FOUNDER_APPROVED" and not approved:
            errors.append(f"{slot}: FOUNDER_APPROVED 缺雙重批准")
        asset_path, declared_sha = item.get("sourceFile"), item.get("sha256")
        if asset_path is None:
            if declared_sha is not None:
                errors.append(f"{slot}: 沒有原始檔不得提供 SHA")
            blockers.append(f"{slot}: 缺獨立原生來源檔")
        else:
            path = Path(asset_path)
            resolved = (root / path).resolve()
            if path.is_absolute() or not resolved.is_relative_to(root):
                errors.append(f"{slot}: 不安全的來源檔路徑")
                continue
            if not resolved.is_file():
                blockers.append(f"{slot}: 來源檔目前不可存取")
            else:
                actual = hashlib.sha256(resolved.read_bytes()).hexdigest()
                if not isinstance(declared_sha, str) or actual != declared_sha.lower():
                    errors.append(f"{slot}: 來源 SHA-256 不符")
        if not approved:
            blockers.append(f"{slot}: 欠缺人工藝術與來源批准")
        if not item.get("assetId"):
            blockers.append(f"{slot}: 正式 Asset ID 未完成權威對照")
    for name in HOLD_FIELDS:
        if slice_data.get(name) != "HOLD":
            errors.append(f"{name}: 本隔離批次不可解除權威 HOLD")
    for name in APPROVAL_FIELDS:
        if document.get("releaseApprovals", {}).get(name) is not False:
            errors.append(f"{name}: 本隔離批次不得聲稱實機或藝術批准")
        blockers.append(f"{name}: 尚未取得真實驗收證據")
    return errors, blockers


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", default="studio/registry/forest_slice_01.json")
    parser.add_argument("--root", default=".")
    parser.add_argument("--mode", choices=["structure", "release"], default="structure")
    parser.add_argument("--report", help="optional JSON report file")
    args = parser.parse_args()
    try:
        document = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
        errors, blockers = verify(document, Path(args.root), release=args.mode == "release")
    except (OSError, ValueError, TypeError) as exc:
        errors, blockers = [f"不能讀取工程契約：{exc}"], []
    status = ("FAIL_STRUCTURE" if errors else
              "BLOCKED_RELEASE" if args.mode == "release" and blockers else
              "SPEC_STRUCTURE_PASS__ART_NOT_VERIFIED__RELEASE_HOLD" if blockers else
              "STRUCTURE_PASS")
    result = {"status": status, "mode": args.mode, "errors": errors, "releaseBlockers": blockers}
    print(json.dumps(result, ensure_ascii=False, indent=2))
    if args.report:
        out = Path(args.report)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 2 if errors else 4 if args.mode == "release" and blockers else 0


if __name__ == "__main__":
    raise SystemExit(main())
